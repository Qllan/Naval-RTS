def entry(key):
    """(категория, заголовок, текст, характеристики) или None."""
    if key in _TEXT:
        cat, title, text = _TEXT[key]
        return cat, title, text, []
    if key.startswith("module:"):
        m = MODULES.get(key[7:])
        if m is None:
            return None
        size = SIZE_NAME[m.size]
        title = m.name if m.name.endswith(f" {size}") else f"{m.name} {size}"
        text = f"{CATEGORY_NAME[m.category]}. {m.desc}".strip()
        stats = module_stats(m) + [f"Масса {m.mass:g}, энергия {m.upkeep:g}/с, цена {m.price} КК"]
        return "Модули", title, text, stats
    if key.startswith("res:"):
        r = RESOURCES.get(key[4:])
        if r is None:
            return None
        return "Ресурсы", r.name, f"Базовая цена в порту — {r.price} КК за единицу.", []
    return None


def all_keys():
    return list(_TEXT) + [f"module:{k}" for k in MODULES] + [f"res:{k}" for k in RESOURCES]
